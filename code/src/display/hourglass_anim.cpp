static const unsigned char* const _frames[FRAME_COUNT] = {
    _hourglass_frame_0, _hourglass_frame_1, _hourglass_frame_2, _hourglass_frame_3,
    _hourglass_frame_4, _hourglass_frame_5, _hourglass_frame_6
};


static uint8_t  _frameIndex = 0;
static uint32_t _lastFrameMs = 0;
static bool     _wasActive = false;


void hourglassAnimDraw(U8G2& display, bool active) {
    if (!active) {
        _wasActive = false;
        return;
    }

    uint32_t now = millis();

    if (!_wasActive) {
        _frameIndex = 0;
        _lastFrameMs = now;
        _wasActive = true;
    } else if (now - _lastFrameMs >= FRAME_INTERVAL_MS) {
        _lastFrameMs = now;
        _frameIndex = (_frameIndex + 1) % FRAME_COUNT;
    }

    display.drawXBMP(0, 0, ICON_SIZE, ICON_SIZE, _frames[_frameIndex]);
}